# 1. выборки X1 из нормального распределения
set.seed(42)
N <- 200
a1 <- 5
S1 <- 2
X1 <- rnorm(N, a1, S1)

# 2. коэффициенты корреляции
r1 <- 0.15  # из интервала [0.1; 0.2]
r2 <- 0.75  # из интервала [0.6; 0.9]

# 3. выборка X2 и X3 с коэффициентами корреляции
a2 <- 3
S2 <- 1.5

X2 <- r1 * X1 + sqrt(1 - r1^2) * rnorm(N, a2, S2)
X3 <- r2 * X1 + sqrt(1 - r2^2) * rnorm(N, a2, S2)

# 4. диаграммы рассеяния
par(mfrow = c(1, 2))
plot(X1, X2, main = "Диаграмма рассеяния X1 и X2", 
     xlab = "X1", ylab = "X2", pch = 19, col = "blue")
abline(lm(X2 ~ X1), col = "red", lwd = 2)

plot(X1, X3, main = "Диаграмма рассеяния X1 и X3", 
     xlab = "X1", ylab = "X3", pch = 19, col = "green")
abline(lm(X3 ~ X1), col = "red", lwd = 2)

# 5. выборочные парные коэффициенты корреляции
r_hat1 <- cor(X1, X2)
r_hat2 <- cor(X1, X3)

cat("Выборочный коэффициент корреляции r1 (X1, X2):", r_hat1, "\n")
cat("Выборочный коэффициент корреляции r2 (X1, X3):", r_hat2, "\n")

# 6. расчет статистик Стьюдента и проверка гипотезы о наличии корреляционной связи
t_stat1 <- r_hat1 * sqrt((N - 2) / (1 - r_hat1^2))
t_stat2 <- r_hat2 * sqrt((N - 2) / (1 - r_hat2^2))

p_value1 <- 2 * (1 - pt(abs(t_stat1), N - 2))
p_value2 <- 2 * (1 - pt(abs(t_stat2), N - 2))

cat("\nПроверка гипотезы о наличии корреляционной связи:\n")
cat("X1 и X2: t-статистика =", t_stat1, ", p-значение =", p_value1, "\n")
cat("X1 и X3: t-статистика =", t_stat2, ", p-значение =", p_value2, "\n")

if (p_value1 < 0.05) {
  cat("Для пары X1-X2: корреляционная связь статистически значима\n")
} else {
  cat("Для пары X1-X2: корреляционная связь не значима\n")
}

if (p_value2 < 0.05) {
  cat("Для пары X1-X3: корреляционная связь статистически значима\n")
} else {
  cat("Для пары X1-X3: корреляционная связь не значима\n")
}

# 7. доверительный интервал для корреляционного коэффициента с помощью Z-преобразования Фишера
# Для r_hat1
z1 <- 0.5 * log((1 + r_hat1) / (1 - r_hat1))
se_z1 <- 1 / sqrt(N - 3)
z_lower1 <- z1 - qnorm(0.975) * se_z1
z_upper1 <- z1 + qnorm(0.975) * se_z1

r_lower1 <- (exp(2 * z_lower1) - 1) / (exp(2 * z_lower1) + 1)
r_upper1 <- (exp(2 * z_upper1) - 1) / (exp(2 * z_upper1) + 1)

# для r_hat2
z2 <- 0.5 * log((1 + r_hat2) / (1 - r_hat2))
se_z2 <- 1 / sqrt(N - 3)
z_lower2 <- z2 - qnorm(0.975) * se_z2
z_upper2 <- z2 + qnorm(0.975) * se_z2

r_lower2 <- (exp(2 * z_lower2) - 1) / (exp(2 * z_lower2) + 1)
r_upper2 <- (exp(2 * z_upper2) - 1) / (exp(2 * z_upper2) + 1)

cat("\nДоверительные интервалы для коэффициентов корреляции (95%):\n")
cat("X1 и X2: [", r_lower1, ";", r_upper1, "]\n")
cat("X1 и X3: [", r_lower2, ";", r_upper2, "]\n")
